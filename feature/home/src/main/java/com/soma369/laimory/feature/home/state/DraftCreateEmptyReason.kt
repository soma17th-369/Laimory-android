package com.soma369.laimory.feature.home.state

/**
 * 확인 다이얼로그가 비어 `만들기` 를 끈 이유. 말풍선 문구와 중단 사유가 갈린다.
 *
 * 보내는 쪽에서는 둘 다 "보낼 것이 없다" 로 같다. 다만 처음부터 없던 사람에게 "모두 뺐다" 고 하거나, 직접 뺀 사람에게
 * "아직 모인 것이 없다" 고 하면 사실과 다르다.
 */
enum class DraftCreateEmptyReason {
    /** 기록 범위에 만들 거리(사진·일정·위치·알림)가 처음부터 없다. */
    NO_DATA,

    /** 모인 것은 있었지만 사용자가 홈에서 모두 뺐다. 걸음만 남은 것도 여기다. */
    ALL_EXCLUDED,
}
