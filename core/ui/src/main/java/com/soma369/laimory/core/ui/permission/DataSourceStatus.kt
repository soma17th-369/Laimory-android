package com.soma369.laimory.core.ui.permission

/**
 * 데이터 소스 하나의 현재 권한 상태. 화면이 **무엇을 보여줄지**만 정한다.
 *
 * 허용/미허용 이분법을 쓰지 않는다 — 사진은 일부만 고를 수 있고, 위치는 전경만 열려 있을 수
 * 있으며, 알림 접근 설정이 아예 없는 기기도 있다. 이 셋을 모두 `미허용` 으로 뭉치면 설정 화면이
 * "허용해 주세요" 라고만 말하는데, 정작 사용자가 할 수 있는 일은 셋 다 다르다.
 *
 * 다음에 무엇을 눌러야 하는지는 [DataPermissionAction] 이 따로 정한다. 상태와 행동을 한
 * enum 에 섞으면 `전경만 허용됨` 처럼 상태는 같은데 기기 버전에 따라 행동만 갈리는 경우를
 * 표현할 수 없다.
 */
enum class DataSourceStatus {
    /** 이 소스가 필요로 하는 것을 모두 받았다. */
    GRANTED,

    /** 일부만 열려 있다 — 사진 일부 선택, 위치 전경만, 활동 인식 거부 등. 수집은 되지만 좁다. */
    LIMITED,

    /** 아직 받지 못했다. 앱이나 시스템 설정에서 열 수 있다. */
    DENIED,

    /** 이 기기에서는 열 방법이 없다 — 알림 접근 설정이 없는 기기, Health Connect 미지원 등. */
    UNSUPPORTED,
}
