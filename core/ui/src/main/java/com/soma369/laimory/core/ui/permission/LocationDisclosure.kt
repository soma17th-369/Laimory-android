package com.soma369.laimory.core.ui.permission

/**
 * 위치 권한을 요청하기 직전에 보여 주는 명시적 공개(Prominent Disclosure).
 *
 * Play 정책(백그라운드 위치)은 런타임 권한 요청 **전에**, 메뉴를 찾아가지 않아도 보이는 자리에서
 * 네 가지를 밝히라고 요구한다 — `위치` 라는 말, 앱이 닫혀 있거나 쓰지 않을 때도 수집한다는 사실,
 * 그 위치를 쓰는 기능, 쓰임새. 하나라도 빠지면 업데이트가 거부된다.
 *
 * 위치를 요청하는 자리(홈 위치 카드 · 온보딩 위치 장 · 설정 위치 시트)가 모두 이 값을 쓴다 —
 * 자리마다 문구를 따로 두면 한 곳만 고쳐지고 나머지가 다시 걸린다.
 */
object LocationDisclosure {
    const val TITLE = "위치 정보 수집 안내"

    /**
     * 첫 문장은 Play 권장 문구 형식을 따른다. 다듬더라도 위의 네 요소는 남겨야 한다.
     *
     * 신체 활동을 함께 적는 이유는 위치 요청이 이동수단 인식을 같은 창에 싣기 때문이다.
     */
    const val BODY =
        "라이모리는 앱이 종료되었거나 사용 중이 아닐 때도 위치 데이터를 수집하여, " +
            "머문 장소와 이동 경로를 하루 타임라인에 기록하는 기능을 지원합니다.\n\n" +
            "수집한 위치는 타임라인을 만들 때 서버로 전송되어 AI가 하루를 정리하는 데 쓰입니다. " +
            "이동 수단(걷기·차량)을 구분하려고 신체 활동 정보도 함께 사용합니다."

    /**
     * 이 단계에서 요청하기 전에 고지가 필요한지.
     *
     * 받을 것이 남아 있으면 그 요청은 시스템 창이든 이 앱의 위치 권한 화면이든 런타임 요청이다.
     * 이미 다 받았으면 띄울 이유가 없다.
     */
    fun isNeededFor(step: LocationPermissionStep): Boolean = step != LocationPermissionStep.GRANTED
}
