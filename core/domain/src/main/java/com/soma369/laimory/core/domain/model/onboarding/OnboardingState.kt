package com.soma369.laimory.core.domain.model.onboarding

/**
 * 설치 단위 온보딩 진행 상태.
 *
 * 판정의 정본은 **로컬 앱 설치**다 — Android 권한이 설치에 붙기 때문이다. 같은 설치에서
 * 로그아웃·탈퇴·계정 전환이 있어도 다시 띄우지 않고, 재설치·앱 데이터 삭제로 권한이 초기화되면
 * 온보딩도 함께 초기화되는 것이 정상이다.
 *
 * 실제 권한 허용 여부는 여기에 담지 않는다. 사용자가 시스템 설정에서 언제든 바꿀 수 있어
 * 복제해 두면 곧 어긋난다 — 권한의 단일 권위는 Android 다.
 */
data class OnboardingState(
    /** 마지막 CTA 를 눌러 온보딩을 끝냈는지. */
    val isCompleted: Boolean = false,
    /**
     * 마지막으로 본 페이지의 키. 중간에 나갔다 오면 여기서 이어 본다.
     *
     * 순번이 아니라 키로 저장한다 — 페이지 목록은 데이터라 앱 버전 사이에 항목이 늘거나 순서가
     * 바뀔 수 있고, 그때 순번은 **예외 없이 엉뚱한 페이지**를 가리킨다. 모르는 키는 첫 장으로
     * 되돌리면 그만이다.
     */
    val lastPageKey: String? = null,
)
